-- Plant names people actually use (2026-10-30). The catalog helps people find
-- a plant; it never blocks a quotation request.
-- plant_search_key: one normal form for matching (case, punctuation, spacing;
--   any script). Typos are matched by trigram similarity on it.
-- plant_aliases: other names of a catalog plant (local/regional, common,
--   synonym, trade, frequent misspelling), maintained by admins or created
--   when a customer-entered name is linked to a plant.
-- plant_suggestions is the registry of names customers could not find:
--   quotation items point at it; linking it to a plant later never changes
--   those items (history stays as entered). MERGED folds a duplicate name
--   into another suggestion.
-- quotation_items / order_items: plant_id is optional; a custom item keeps
--   the exact name entered (custom_plant_name) and its specifications.

CREATE OR REPLACE FUNCTION public.plant_search_key(name text) RETURNS text
    LANGUAGE sql IMMUTABLE PARALLEL SAFE
    AS $$ SELECT btrim(regexp_replace(lower(coalesce(name, '')), '[^[:alnum:]]+', ' ', 'g')) $$;
COMMENT ON FUNCTION public.plant_search_key(text) IS 'Normal form of a plant name for matching: lower case, punctuation and runs of spaces to one space';

CREATE TABLE IF NOT EXISTS public.plant_aliases (
    plant_alias_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id bigint NOT NULL REFERENCES public.plants(plant_id) ON DELETE CASCADE,
    name character varying(255) NOT NULL,
    search_key text GENERATED ALWAYS AS (public.plant_search_key(name)) STORED,
    alias_type character varying(20) DEFAULT 'LOCAL' NOT NULL,
    language character varying(10),
    region character varying(80),
    source character varying(20) DEFAULT 'ADMIN' NOT NULL,
    plant_suggestion_id bigint REFERENCES public.plant_suggestions(suggestion_id) ON DELETE SET NULL,
    is_active boolean DEFAULT true NOT NULL,
    created_by_user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_plant_aliases_type CHECK (alias_type IN ('COMMON', 'LOCAL', 'SYNONYM', 'TRADE', 'MISSPELLING')),
    CONSTRAINT ck_plant_aliases_source CHECK (source IN ('ADMIN', 'SUGGESTION')),
    CONSTRAINT ck_plant_aliases_name CHECK (btrim(name) <> '')
);
-- One active alias per name per plant (the same local name may mean two plants).
CREATE UNIQUE INDEX IF NOT EXISTS uq_plant_aliases_active
    ON public.plant_aliases (plant_id, search_key) WHERE is_active;
CREATE INDEX IF NOT EXISTS idx_plant_aliases_search
    ON public.plant_aliases USING gin (search_key public.gin_trgm_ops) WHERE is_active;
CREATE INDEX IF NOT EXISTS idx_plant_aliases_plant ON public.plant_aliases (plant_id);
COMMENT ON TABLE public.plant_aliases IS 'Other names of a catalog plant (local, common, synonym, trade, misspelling)';

CREATE INDEX IF NOT EXISTS idx_plants_search_common
    ON public.plants USING gin (public.plant_search_key(common_name) public.gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_plants_search_scientific
    ON public.plants USING gin (public.plant_search_key(scientific_name) public.gin_trgm_ops);


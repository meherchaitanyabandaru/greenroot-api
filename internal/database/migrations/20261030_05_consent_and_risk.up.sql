CREATE TABLE IF NOT EXISTS public.risk_signals (
    risk_signal_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signal_code character varying(40) NOT NULL,
    entity_type character varying(20) NOT NULL,
    entity_id bigint NOT NULL,
    risk_level character varying(20) NOT NULL,
    status character varying(20) DEFAULT 'OPEN' NOT NULL,
    details jsonb DEFAULT '{}'::jsonb NOT NULL,
    is_hold boolean DEFAULT false NOT NULL,
    resolution_note text,
    resolved_by_user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
    resolved_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_risk_signals_entity CHECK (entity_type IN ('ORDER', 'QUOTATION', 'NURSERY', 'USER', 'DRIVER')),
    CONSTRAINT ck_risk_signals_level CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH', 'CONFIRMED_FRAUD')),
    CONSTRAINT ck_risk_signals_status CHECK (status IN ('OPEN', 'UNDER_REVIEW', 'RESOLVED', 'DISMISSED'))
);
-- One open signal per finding: the detector re-running adds nothing.
CREATE UNIQUE INDEX IF NOT EXISTS uq_risk_signals_open
    ON public.risk_signals (signal_code, entity_type, entity_id) WHERE status IN ('OPEN', 'UNDER_REVIEW');
CREATE INDEX IF NOT EXISTS idx_risk_signals_queue ON public.risk_signals (status, risk_level, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_risk_signals_hold ON public.risk_signals (entity_type, entity_id) WHERE is_hold;
COMMENT ON TABLE public.risk_signals IS 'Unusual activity for admin review; holds pause that order''s dispatch';

CREATE TABLE IF NOT EXISTS public.risk_signal_notes (
    risk_signal_note_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    risk_signal_id bigint NOT NULL REFERENCES public.risk_signals(risk_signal_id),
    user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
    action character varying(30) NOT NULL,
    note text NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_risk_signal_notes_signal ON public.risk_signal_notes (risk_signal_id, created_at);
DROP TRIGGER IF EXISTS trg_risk_signal_notes_append_only ON public.risk_signal_notes;
CREATE TRIGGER trg_risk_signal_notes_append_only BEFORE UPDATE OR DELETE ON public.risk_signal_notes
    FOR EACH ROW EXECUTE FUNCTION public.forbid_change();
COMMENT ON TABLE public.risk_signal_notes IS 'Investigation notes and decisions on a risk signal (append-only)';

-- Consent, responsibility and risk (2026-10-30).
-- consent_records: what each party confirmed at each step, with the exact
--   wording of that version. Rows are never changed or deleted (trigger):
--   a new wording is a new version; history stays as it was agreed.
-- dispatches.requires_consent: trips created from now on need the driver's
--   confirmation before starting; trips that already existed do not.
-- risk_rules / risk_signals / risk_signal_notes: unusual activity flagged for
--   admins (never an automatic fraud verdict), their decisions and notes.

CREATE TABLE IF NOT EXISTS public.consent_records (
    consent_record_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consent_type character varying(40) NOT NULL,
    consent_version integer NOT NULL,
    statements jsonb NOT NULL,
    user_id bigint NOT NULL REFERENCES public.users(user_id),
    user_role character varying(30) NOT NULL,
    order_id bigint REFERENCES public.orders(order_id),
    dispatch_id bigint REFERENCES public.dispatches(dispatch_id),
    quotation_id bigint REFERENCES public.quotations(quotation_id),
    evidence jsonb DEFAULT '[]'::jsonb NOT NULL,
    ip_address character varying(64),
    user_agent character varying(255),
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_consent_records_type CHECK (consent_type IN ('SELLER_LOADING', 'DRIVER_DISPATCH', 'BUYER_QUOTATION_ACCEPT', 'BUYER_DELIVERY')),
    CONSTRAINT ck_consent_records_subject CHECK (order_id IS NOT NULL OR dispatch_id IS NOT NULL OR quotation_id IS NOT NULL),
    CONSTRAINT ck_consent_records_statements CHECK (jsonb_typeof(statements) = 'array' AND jsonb_array_length(statements) > 0)
);
-- One record per party, step and wording version (a retry adds nothing).
CREATE UNIQUE INDEX IF NOT EXISTS uq_consent_records_once
    ON public.consent_records (consent_type, consent_version, user_id, order_id, dispatch_id, quotation_id) NULLS NOT DISTINCT;
CREATE INDEX IF NOT EXISTS idx_consent_records_order ON public.consent_records (order_id) WHERE order_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_consent_records_dispatch ON public.consent_records (dispatch_id) WHERE dispatch_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_consent_records_quotation ON public.consent_records (quotation_id) WHERE quotation_id IS NOT NULL;
COMMENT ON TABLE public.consent_records IS 'Confirmations given at each step with the exact wording (append-only)';

CREATE OR REPLACE FUNCTION public.forbid_change() RETURNS trigger
    LANGUAGE plpgsql
    AS $$ BEGIN RAISE EXCEPTION '% rows cannot be changed or deleted', TG_TABLE_NAME USING ERRCODE = 'check_violation'; END $$;
DROP TRIGGER IF EXISTS trg_consent_records_append_only ON public.consent_records;
CREATE TRIGGER trg_consent_records_append_only BEFORE UPDATE OR DELETE ON public.consent_records
    FOR EACH ROW EXECUTE FUNCTION public.forbid_change();

ALTER TABLE public.dispatches ADD COLUMN IF NOT EXISTS requires_consent boolean DEFAULT false NOT NULL;
ALTER TABLE public.dispatches ALTER COLUMN requires_consent SET DEFAULT true;
COMMENT ON COLUMN public.dispatches.requires_consent IS 'The driver confirms the load before starting (false for trips made before 2026-10-30)';

CREATE TABLE IF NOT EXISTS public.risk_rules (
    risk_rule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signal_code character varying(40) NOT NULL,
    is_enabled boolean DEFAULT true NOT NULL,
    threshold numeric(15,2) NOT NULL,
    risk_level character varying(20) NOT NULL,
    description text NOT NULL,
    updated_by_user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT risk_rules_signal_code_key UNIQUE (signal_code),
    -- CONFIRMED_FRAUD is only ever an admin's finding, never a rule's.
    CONSTRAINT ck_risk_rules_level CHECK (risk_level IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_risk_rules_threshold CHECK (threshold > 0)
);

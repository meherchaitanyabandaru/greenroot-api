-- Image rules per upload category (2026-10-30). Admins tune them within safe
-- bounds the API enforces (internal/common/imagepolicy); the API checks every
-- upload against them. A change applies to new uploads only: stored images
-- are never modified. Every saved version is kept in image_policy_versions.
CREATE TABLE IF NOT EXISTS public.image_policies (
    image_policy_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category character varying(30) NOT NULL,
    max_side integer NOT NULL,
    min_side integer NOT NULL,
    quality integer NOT NULL,
    max_bytes bigint NOT NULL,
    allowed_formats jsonb NOT NULL,
    is_compression_enabled boolean DEFAULT true NOT NULL,
    version integer DEFAULT 1 NOT NULL,
    updated_by_user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT image_policies_category_key UNIQUE (category),
    CONSTRAINT ck_image_policies_category CHECK (category IN ('SELFIE', 'MARKET_AD', 'NURSERY_BRANDING', 'DELIVERY_PROOF', 'LOADING_PROOF', 'DRIVER_LICENCE', 'ATTACHMENT')),
    -- The widest bounds; per-category floors (licence readability) are in the API.
    CONSTRAINT ck_image_policies_bounds CHECK (max_side BETWEEN 320 AND 4096 AND min_side BETWEEN 64 AND max_side
        AND quality BETWEEN 50 AND 95 AND max_bytes BETWEEN 51200 AND 10485760),
    CONSTRAINT ck_image_policies_formats CHECK (jsonb_typeof(allowed_formats) = 'array' AND jsonb_array_length(allowed_formats) > 0
        AND allowed_formats <@ '["JPEG", "PNG"]'::jsonb)
);
COMMENT ON TABLE public.image_policies IS 'Upload rules per image category; the API is the final authority';

CREATE TABLE IF NOT EXISTS public.image_policy_versions (
    image_policy_version_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_policy_id bigint NOT NULL REFERENCES public.image_policies(image_policy_id),
    category character varying(30) NOT NULL,
    version integer NOT NULL,
    policy jsonb NOT NULL,
    changed_by_user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
    change_note text,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT image_policy_versions_category_version_key UNIQUE (category, version)
);
COMMENT ON TABLE public.image_policy_versions IS 'Every saved version of each image policy (who, when, why)';


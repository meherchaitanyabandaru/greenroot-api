-- Vehicle ownership is independent of driver accounts (2026-10-30).
-- vehicle_owners: who owns a lorry. An owner needs no GreenRoot account;
--   user_id is set only when the owner is also a GreenRoot user (an owner who
--   drives uses one normal driver account).
-- vehicle_drivers: which drivers may take trips with which lorry. A lorry has
--   many drivers and a driver may drive lorries of different owners; GreenRoot
--   approves each link.
-- vehicles.approval_status: GreenRoot's check of the lorry itself (same
--   vocabulary as drivers.approval_status).
-- dispatch_assignments is not touched: no code reads or writes it (see API.md).

CREATE TABLE IF NOT EXISTS public.vehicle_owners (
    vehicle_owner_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(255) NOT NULL,
    mobile character varying(20),
    user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
    notes text,
    created_by_user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_vehicle_owners_name CHECK (btrim(name) <> '')
);
-- One owner record per mobile number and per GreenRoot account.
CREATE UNIQUE INDEX IF NOT EXISTS uq_vehicle_owners_mobile
    ON public.vehicle_owners (mobile) WHERE mobile IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_vehicle_owners_user_id
    ON public.vehicle_owners (user_id) WHERE user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_vehicle_owners_name
    ON public.vehicle_owners USING gin (name public.gin_trgm_ops);
COMMENT ON TABLE public.vehicle_owners IS 'Lorry owners; an owner needs no GreenRoot account (user_id only when they also use the app)';

ALTER TABLE public.vehicles ADD COLUMN IF NOT EXISTS owner_id bigint REFERENCES public.vehicle_owners(vehicle_owner_id) ON DELETE SET NULL;
ALTER TABLE public.vehicles ADD COLUMN IF NOT EXISTS approval_status character varying(20) DEFAULT 'PENDING' NOT NULL;
ALTER TABLE public.vehicles ADD COLUMN IF NOT EXISTS approved_by_user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL;
ALTER TABLE public.vehicles ADD COLUMN IF NOT EXISTS approved_at timestamp with time zone;
ALTER TABLE public.vehicles ADD COLUMN IF NOT EXISTS approval_note text;
ALTER TABLE public.vehicles DROP CONSTRAINT IF EXISTS ck_vehicles_approval_status;
ALTER TABLE public.vehicles ADD CONSTRAINT ck_vehicles_approval_status
    CHECK (approval_status IN ('PENDING', 'APPROVED', 'REJECTED', 'SUSPENDED'));
CREATE INDEX IF NOT EXISTS idx_vehicles_owner_id ON public.vehicles (owner_id) WHERE owner_id IS NOT NULL;
COMMENT ON COLUMN public.vehicles.owner_name IS 'Deprecated 2026-10-30: copied into vehicle_owners; read owner via owner_id';
COMMENT ON COLUMN public.vehicles.mobile IS 'Deprecated 2026-10-30: copied into vehicle_owners; read owner via owner_id';

CREATE TABLE IF NOT EXISTS public.vehicle_drivers (
    vehicle_driver_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id bigint NOT NULL REFERENCES public.vehicles(vehicle_id) ON DELETE CASCADE,
    driver_user_id bigint NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    status character varying(20) DEFAULT 'PENDING' NOT NULL,
    decided_by_user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
    decided_at timestamp with time zone,
    decision_note text,
    removed_by_user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
    removed_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_vehicle_drivers_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'SUSPENDED', 'REMOVED'))
);
-- One open link per driver and lorry; rejected and removed ones stay as history.
CREATE UNIQUE INDEX IF NOT EXISTS uq_vehicle_drivers_open
    ON public.vehicle_drivers (vehicle_id, driver_user_id) WHERE status IN ('PENDING', 'APPROVED', 'SUSPENDED');
CREATE INDEX IF NOT EXISTS idx_vehicle_drivers_driver ON public.vehicle_drivers (driver_user_id, status);
CREATE INDEX IF NOT EXISTS idx_vehicle_drivers_status_created ON public.vehicle_drivers (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_dispatches_vehicle_active ON public.dispatches (vehicle_id)
    WHERE vehicle_id IS NOT NULL AND status IN ('ACCEPTED', 'DISPATCHED', 'IN_TRANSIT');
COMMENT ON TABLE public.vehicle_drivers IS 'Drivers allowed to take trips with a lorry; GreenRoot approves each link';

-- Backfill 1: owners from the owner name/mobile the lorry carried (copied from
-- the driver who registered it), linked to that user when the mobile matches.
INSERT INTO public.vehicle_owners (name, mobile, user_id)
SELECT DISTINCT ON (btrim(v.mobile))
       COALESCE(NULLIF(btrim(v.owner_name), ''), btrim(v.mobile)), btrim(v.mobile), u.user_id
FROM public.vehicles v
LEFT JOIN public.users u ON u.mobile = btrim(v.mobile)
WHERE NULLIF(btrim(v.mobile), '') IS NOT NULL
ORDER BY btrim(v.mobile), v.updated_at DESC NULLS LAST
ON CONFLICT DO NOTHING;
UPDATE public.vehicles v SET owner_id = o.vehicle_owner_id
FROM public.vehicle_owners o
WHERE v.owner_id IS NULL AND o.mobile = btrim(v.mobile);
-- Name only, no mobile: one owner record per lorry (names are not unique).
WITH named AS (
    SELECT vehicle_id, btrim(owner_name) AS name FROM public.vehicles
    WHERE owner_id IS NULL AND NULLIF(btrim(owner_name), '') IS NOT NULL
), created AS (
    INSERT INTO public.vehicle_owners (name, notes)
    SELECT name, 'migrated from vehicle ' || vehicle_id FROM named
    RETURNING vehicle_owner_id, notes
)
UPDATE public.vehicles v SET owner_id = c.vehicle_owner_id
FROM created c WHERE c.notes = 'migrated from vehicle ' || v.vehicle_id;

-- Backfill 2: each driver's registered lorry becomes a link; approved drivers
-- were already taking trips with it, so link and lorry start approved.
INSERT INTO public.vehicle_drivers (vehicle_id, driver_user_id, status, decided_at, decision_note)
SELECT DISTINCT ON (v.vehicle_id, d.user_id) v.vehicle_id, d.user_id,
       CASE WHEN d.approval_status = 'APPROVED' THEN 'APPROVED' ELSE 'PENDING' END,
       CASE WHEN d.approval_status = 'APPROVED' THEN CURRENT_TIMESTAMP END,
       'migrated from driver registration'
FROM public.drivers d
JOIN public.vehicles v ON upper(btrim(v.vehicle_number)) = upper(btrim(d.vehicle_number))
WHERE d.user_id IS NOT NULL AND COALESCE(d.status::text, '') = 'ACTIVE'
  AND COALESCE(d.approval_status, '') <> 'REJECTED'
ORDER BY v.vehicle_id, d.user_id, d.driver_id DESC
ON CONFLICT DO NOTHING;
UPDATE public.vehicles v SET approval_status = 'APPROVED', approved_at = CURRENT_TIMESTAMP,
       approval_note = 'migrated: in use by an approved driver'
WHERE v.approval_status = 'PENDING'
  AND EXISTS (SELECT 1 FROM public.vehicle_drivers vd WHERE vd.vehicle_id = v.vehicle_id AND vd.status = 'APPROVED');

-- Why each link can or cannot take a trip now. blocked_reason NULL = eligible.
-- Trip-specific checks (the lorry type a trip asks for) stay in the API.
CREATE OR REPLACE VIEW public.driver_vehicle_eligibility AS
SELECT vd.vehicle_driver_id,
       vd.driver_user_id,
       vd.status AS link_status,
       v.vehicle_id,
       v.vehicle_number,
       v.vehicle_type,
       v.capacity_kg,
       v.status AS vehicle_status,
       v.approval_status AS vehicle_approval_status,
       d.license_expiry_date,
       EXISTS (SELECT 1 FROM public.dispatches t
               WHERE t.vehicle_id = v.vehicle_id AND t.status IN ('ACCEPTED', 'DISPATCHED', 'IN_TRANSIT')) AS is_on_active_trip,
       CASE
           WHEN vd.status = 'PENDING' THEN 'LINK_PENDING'
           WHEN vd.status = 'SUSPENDED' THEN 'LINK_SUSPENDED'
           WHEN v.approval_status <> 'APPROVED' THEN 'VEHICLE_NOT_APPROVED'
           WHEN v.status = 'MAINTENANCE' THEN 'VEHICLE_MAINTENANCE'
           WHEN COALESCE(v.status, 'ACTIVE') <> 'ACTIVE' THEN 'VEHICLE_INACTIVE'
           WHEN d.license_expiry_date IS NOT NULL AND d.license_expiry_date < CURRENT_DATE THEN 'LICENCE_EXPIRED'
           WHEN EXISTS (SELECT 1 FROM public.dispatches t
                        WHERE t.vehicle_id = v.vehicle_id AND t.status IN ('ACCEPTED', 'DISPATCHED', 'IN_TRANSIT')) THEN 'VEHICLE_ON_TRIP'
       END AS blocked_reason
FROM public.vehicle_drivers vd
JOIN public.vehicles v ON v.vehicle_id = vd.vehicle_id
LEFT JOIN LATERAL (
    SELECT license_expiry_date FROM public.drivers
    WHERE user_id = vd.driver_user_id ORDER BY driver_id DESC LIMIT 1
) d ON true
WHERE vd.status IN ('PENDING', 'APPROVED', 'SUSPENDED');
COMMENT ON VIEW public.driver_vehicle_eligibility IS 'Open driver-lorry links and why each may (blocked_reason NULL) or may not take a trip';

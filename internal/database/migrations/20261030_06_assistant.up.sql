-- Mango assistant (2026-10-30).
-- assistant_usage_events: one row per AI provider call (speech to text, model
--   reply, read aloud) with units and an estimated cost, for limits and the
--   budget. No message text, transcript or audio is stored.
-- assistant_actions: a change Mango proposed and the user has not yet
--   confirmed. It runs only after the user confirms, as that user, through
--   the normal endpoint (which checks permission and state again).

CREATE TABLE IF NOT EXISTS public.assistant_usage_events (
    assistant_usage_event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
    usage_kind character varying(10) NOT NULL,
    model character varying(80) NOT NULL,
    input_tokens integer DEFAULT 0 NOT NULL,
    output_tokens integer DEFAULT 0 NOT NULL,
    cached_input_tokens integer DEFAULT 0 NOT NULL,
    audio_seconds numeric(8,2) DEFAULT 0 NOT NULL,
    characters integer DEFAULT 0 NOT NULL,
    estimated_cost_usd numeric(12,6) DEFAULT 0 NOT NULL,
    request_id character varying(100),
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_assistant_usage_events_kind CHECK (usage_kind IN ('STT', 'LLM', 'TTS')),
    CONSTRAINT ck_assistant_usage_events_units CHECK (input_tokens >= 0 AND output_tokens >= 0 AND cached_input_tokens >= 0 AND audio_seconds >= 0 AND characters >= 0 AND estimated_cost_usd >= 0)
);
CREATE INDEX IF NOT EXISTS idx_assistant_usage_events_user ON public.assistant_usage_events (user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_assistant_usage_events_created ON public.assistant_usage_events (created_at);
COMMENT ON TABLE public.assistant_usage_events IS 'Mango AI calls: units and estimated cost only, never content';

CREATE TABLE IF NOT EXISTS public.assistant_actions (
    assistant_action_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    action_type character varying(40) NOT NULL,
    target_id bigint NOT NULL,
    summary text NOT NULL,
    status character varying(20) DEFAULT 'PENDING' NOT NULL,
    result_message text,
    expires_at timestamp with time zone NOT NULL,
    decided_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_assistant_actions_type CHECK (action_type IN ('CONFIRM_ORDER')),
    CONSTRAINT ck_assistant_actions_status CHECK (status IN ('PENDING', 'DONE', 'FAILED', 'CANCELLED'))
);
CREATE INDEX IF NOT EXISTS idx_assistant_actions_user ON public.assistant_actions (user_id, created_at);
COMMENT ON TABLE public.assistant_actions IS 'Changes Mango proposed; run only after the user confirms';

-- Community contributions: a plant a user could not find. Admins review them;
-- only an admin action changes the plants master data.
CREATE TABLE IF NOT EXISTS public.plant_suggestions (
    suggestion_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(255) NOT NULL,
    scientific_name character varying(255),
    notes text,
    suggested_by_user_id bigint NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    status character varying(20) DEFAULT 'PENDING' NOT NULL,
    plant_id bigint REFERENCES public.plants(plant_id) ON DELETE SET NULL,
    review_note text,
    reviewed_by_user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
    reviewed_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_plant_suggestions_status CHECK (status IN ('PENDING', 'APPROVED', 'LINKED', 'REJECTED'))
);

CREATE INDEX IF NOT EXISTS idx_plant_suggestions_status_created
    ON public.plant_suggestions (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_plant_suggestions_user_created
    ON public.plant_suggestions (suggested_by_user_id, created_at DESC);
-- One open suggestion per name: repeats are ignored.
CREATE UNIQUE INDEX IF NOT EXISTS uq_plant_suggestions_pending_name
    ON public.plant_suggestions (lower(name)) WHERE status = 'PENDING';

-- Restore the multilingual schema for a manual rollback. Dropped translations
-- cannot be recovered; only future translations can be stored after rollback.
CREATE TABLE IF NOT EXISTS public.languages (
    language_id smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    language_code varchar(10) NOT NULL UNIQUE,
    language_name varchar(100) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.plant_names (
    plant_name_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id bigint NOT NULL REFERENCES public.plants(plant_id) ON DELETE CASCADE,
    language_id smallint NOT NULL REFERENCES public.languages(language_id),
    plant_name varchar(255) NOT NULL,
    description text,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (plant_id, language_id)
);

CREATE INDEX IF NOT EXISTS idx_plant_names_language ON public.plant_names (language_id);
CREATE INDEX IF NOT EXISTS idx_plant_names_name ON public.plant_names (plant_name);


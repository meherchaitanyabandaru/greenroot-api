-- Money that moved at Razorpay but could not be applied here (charged for a
-- subscription a rule now refuses, or a refund Razorpay failed). The webhook
-- answers 200 for these (a retry cannot fix them), so this table, not a log
-- line, is where an admin finds and settles them.
CREATE TABLE IF NOT EXISTS public.payment_issues (
    payment_issue_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_type character varying(30) NOT NULL,
    provider character varying(30) DEFAULT 'razorpay'::character varying NOT NULL,
    provider_order_id character varying(255),
    provider_payment_id character varying(255) NOT NULL,
    provider_refund_id character varying(255),
    user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
    amount numeric(12,2),
    reason text NOT NULL,
    status character varying(20) DEFAULT 'OPEN'::character varying NOT NULL,
    resolution_note text,
    resolved_by_user_id bigint REFERENCES public.users(user_id) ON DELETE SET NULL,
    resolved_at timestamp with time zone,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_payment_issues_issue_type CHECK (issue_type IN ('PAID_NOT_APPLIED', 'REFUND_FAILED')),
    CONSTRAINT ck_payment_issues_status CHECK (status IN ('OPEN', 'RESOLVED')),
    CONSTRAINT ck_payment_issues_resolved CHECK ((status = 'RESOLVED') = (resolved_at IS NOT NULL))
);

COMMENT ON TABLE public.payment_issues IS 'Razorpay money that needs a human: paid but not applied, or a failed refund';

-- One row per payment and kind: webhook redeliveries do not duplicate it.
CREATE UNIQUE INDEX IF NOT EXISTS uq_payment_issues_payment ON public.payment_issues (provider, provider_payment_id, issue_type);
CREATE INDEX IF NOT EXISTS idx_payment_issues_open_created ON public.payment_issues (created_at DESC) WHERE status = 'OPEN';

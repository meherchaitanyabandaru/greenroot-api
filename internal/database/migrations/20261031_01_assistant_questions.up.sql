-- Mango daily question limit (2026-10-31).
-- assistant_question_days: questions answered per user per day (India time,
--   the API computes the date). A slot is reserved atomically before the
--   model is called and given back if no answer is delivered. Counts only,
--   no text. Kept when a user deletes their Mango data: it is what stops the
--   limit from being reset by the user.
-- platform_config: admins change the limit and switch Mango on or off.

CREATE TABLE IF NOT EXISTS public.assistant_question_days (
    assistant_question_day_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(user_id) ON DELETE CASCADE,
    question_date date NOT NULL,
    questions_used integer DEFAULT 0 NOT NULL,
    updated_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT assistant_question_days_user_id_question_date_key UNIQUE (user_id, question_date),
    CONSTRAINT ck_assistant_question_days_used CHECK (questions_used >= 0)
);
COMMENT ON TABLE public.assistant_question_days IS 'Mango questions answered per user per day (India time); counts only';

INSERT INTO public.platform_config (config_key, config_value, data_type, description) VALUES
  ('assistant_enabled',         'true', 'boolean', 'Mango AI on for owners, managers and customers (the API''s AI_ENABLED must also be on)'),
  ('assistant_daily_questions', '5',    'integer', 'Mango AI questions each user may ask per day (India time)')
ON CONFLICT (config_key) DO NOTHING;
